// Generate the fallback-display property from a verified Unicode data file:
//   node tools/unicode/generate-default-ignorables.mjs DerivedCoreProperties.txt > src/unicode_default_ignorables.hpp
import { createHash } from 'node:crypto';
import fs from 'node:fs';

const VERSION = '16.0.0';
const SHA256 = '39d35161f2954497f69e08bdb9e701493f476a3d30222de20028feda36c1dabd';
const data = fs.readFileSync(process.argv[2]);
if (createHash('sha256').update(data).digest('hex') !== SHA256) {
  console.error('Expected pinned Unicode ' + VERSION + ' DerivedCoreProperties.txt');
  process.exit(1);
}
const ranges = [];
for (const line of data.toString('utf8').split(/\r?\n/)) {
  const fields = line.split('#')[0].trim().split(';');
  if (fields.length !== 2 || fields[1].trim() !== 'Default_Ignorable_Code_Point') continue;
  const bounds = fields[0].trim().split('..');
  const lo = parseInt(bounds[0], 16), hi = parseInt(bounds.at(-1), 16);
  if (ranges.length && lo === ranges.at(-1)[1] + 1) ranges.at(-1)[1] = hi;
  else ranges.push([lo, hi]);
}
const hex = value => '0x' + value.toString(16).toUpperCase();
process.stdout.write([
  '// SPDX-License-Identifier: Unicode-3.0',
  '// Generated by tools/unicode/generate-default-ignorables.mjs; Unicode ' + VERSION,
  '// Source: https://www.unicode.org/Public/' + VERSION + '/ucd/DerivedCoreProperties.txt',
  '// SHA-256: ' + SHA256,
  '// Unicode data license: third_party/unicode.LICENSE',
  '#pragma once', '#include <array>', '#include <cstdint>', '', 'namespace pmjs {',
  'inline bool isDefaultIgnorable(std::uint32_t codepoint) {',
  '  static constexpr std::array ranges{',
  ...ranges.map(([lo, hi]) => `    std::array<std::uint32_t, 2>{${hex(lo)}, ${hex(hi)}},`),
  '  };', '  for (const auto& range : ranges) {', '    if (codepoint < range[0]) return false;',
  '    if (codepoint <= range[1]) return true;', '  }', '  return false;', '}', '}  // namespace pmjs', ''
].join('\n'));
